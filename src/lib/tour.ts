/** Раздел по адресу; подсказки — только на главных экранах разделов. */
export function tourFor(pathname: string): TourSection | null {
  const p = pathname.replace(/\/+$/, '') || '/';
  const id = p === '/' ? 'home' : p.slice(1);
  return TOUR[id] ?? null;
}
