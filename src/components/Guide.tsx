/** «Как пользоваться»: все разделы и фишки на одной странице с оглавлением. */
export default function Guide() {
  const { data, mutate, toast, replayOnboarding } = useApp();
  const parts = PARTS.filter((p) => !p.ai || data.ai);
  // Только подсказки: «Что вам нужно?» уже было — его заново — кнопкой рядом.
  const replay = () => {
    mutate(
      (d) => ({ ...d, settings: { ...d.settings, tour_seen: [SETUP_SEEN] } }),
      () => api('settings', 'PATCH', { tour_seen: [SETUP_SEEN] }),
    );
    toast('Подсказки покажутся снова — при входе в каждый раздел');
  };
  return (
    <div className="guide">
      <div className="page-head" style={{ marginBottom: 0 }}>
        <h1 className="h1 display" style={{ flex: 1 }}>
          Как пользоваться
        </h1>
        <button className="btn btn-ghost" type="button" onClick={replay}>
          <Icon name="help" size={18} />
          Показать подсказки заново
        </button>
        <button className="btn btn-ghost" type="button" onClick={replayOnboarding}>
          <Icon name="reset" size={18} />
          Пройти знакомство заново
        </button>
      </div>
      <p style={{ margin: 0, color: 'var(--muted)' }}>LifeDashboard — задачи, напоминания, чек-листы, заметки, кухня, спорт, деньги и отпуска в одном месте. Вот что он умеет.</p>
      <nav className="guide-toc" aria-label="Оглавление">
        {parts.map((p) => (
          <a key={p.id} className="chip" href={`#${p.id}`} style={{ textDecoration: 'none' }}>
            {p.title}
          </a>
        ))}
      </nav>
      {parts.map((p) => (
        <section key={p.id} className={`card${p.ai ? ' ai-card' : ''}`} aria-labelledby={p.id}>
          <div className="card-head" style={{ display: 'flex', alignItems: 'center', gap: 8 }}>
            <h2 className="card-title display" id={p.id}>
              <Icon name={p.icon} />
              {p.title}
            </h2>
            {p.href && (
              <Link href={p.href} style={{ marginLeft: 'auto', fontSize: 'calc(14px * var(--fs))', fontWeight: 600 }}>
                Открыть<span className="sr-only">{` раздел «${p.title}»`}</span>
              </Link>
            )}
          </div>
          <ul>
            {p.points.map((x, i) => (
              <li key={i}>{x}</li>
            ))}
          </ul>
          {p.tip && <div className="guide-tip">{p.tip}</div>}
        </section>
      ))}
      <section className="card" style={{ flexDirection: 'row', alignItems: 'center', gap: 12, flexWrap: 'wrap' }}>
        <span style={{ flex: 1, minWidth: 200 }}>Не нашли ответ или есть идея?</span>
        <Link className="btn btn-primary" href="/support">
          <Icon name="chat" size={18} />
          Написать в поддержку
        </Link>
      </section>
    </div>
  );
}
